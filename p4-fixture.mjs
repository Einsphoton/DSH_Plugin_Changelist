/**
 * Perforce test fixture.
 *
 * `buildP4Fixture()` writes a deterministic fake `p4` next to a recorded
 * workspace under `.changelist-test/p4-fake/`:
 *
 *   run.mjs    the router: it inspects argv (and FAKE_P4_MODE) and prints the
 *              recorded `-ztag` answers below, then exits 0
 *   p4.cmd     the shim the plugin is given as `p4Path` (`<node> run.mjs %*`)
 *   root/      a real directory tree, so the plugin's own `readFile` works
 *   calls.log  one line per invocation, joined argv — this is how a test proves
 *              which commands were issued (e.g. that `fstat //client/...` was
 *              never run)
 *
 * That path is fixed and shared. `buildP4Fixture()` deletes and rewrites the
 * tree, so two suites must never rebuild it concurrently: a parallel build can
 * delete `run.mjs` out from under an in-flight spawn (observed once as a single
 * spurious not-a-workspace failure).
 *
 * Modes, selected with `FAKE_P4_MODE`, cover every error reason:
 *   ok (default) | unreachable | noclient | notworkspace
 *
 * Sandbox note: this authoring environment denies piped child stdio, so
 * `createFakeP4ExecFile()` spawns `node run.mjs …args` with stdout/stderr
 * redirected to files; it is execFile-shaped and only ever ignores the `file`
 * argument after checking that it names the fake.
 */
