// --------------------------------------------------------------------------- build

function writeRootFiles() {
  for (const file of FAKE_P4_FILES) {
    const target = path.join(FAKE_P4_ROOT, ...file.rel.split('/'))
    if (file.deleted) continue // a deleted file is genuinely absent locally
    fs.mkdirSync(path.dirname(target), { recursive: true })
    if (file.binary) fs.writeFileSync(target, Buffer.from(file.bytes))
    else fs.writeFileSync(target, file.text)
  }
}

/**
 * (Re)build the fake p4 and its recorded workspace. Deterministic: every run
 * removes the previous tree and rewrites identical bytes, and truncates the
 * call log.
 * @returns {{ dir: string, root: string, script: string, shim: string, callsLog: string }}
 */
export function buildP4Fixture() {
  fs.rmSync(FAKE_P4_DIR, { recursive: true, force: true })
  fs.mkdirSync(FAKE_P4_ROOT, { recursive: true })
  // A real directory outside the client root: probes run with it as cwd.
  fs.mkdirSync(FAKE_P4_OUTSIDE, { recursive: true })
  fs.mkdirSync(path.join(FAKE_P4_DIR, 'log'), { recursive: true })

  const files = FAKE_P4_FILES.map((file) => ({
    rel: file.rel,
    action: file.action,
    change: file.change,
    type: file.type,
    rev: file.rev,
    haveRev: file.haveRev,
    headRev: file.headRev,
    opened: file.opened,
    binary: Boolean(file.binary),
    bytes: file.bytes ?? null,
    text: file.text ?? '',
  }))
  const changes = FAKE_P4_CHANGES.map((change) => ({ ...change }))
  // Function replacements: the JSON must never be read as a `$` pattern.
  fs.writeFileSync(
    FAKE_P4_SCRIPT,
    ROUTER_SOURCE.replace('__FILES__', () => JSON.stringify(files, null, 2)).replace('__CHANGES__', () =>
      JSON.stringify(changes, null, 2),
    ),
    'utf8',
  )
  fs.writeFileSync(
    FAKE_P4_SHIM,
    ['@echo off', `"${process.execPath}" "%~dp0run.mjs" %*`, ''].join('\r\n'),
    'utf8',
  )
  writeRootFiles()
  fs.writeFileSync(FAKE_P4_CALLS, '')
  return { dir: FAKE_P4_DIR, root: FAKE_P4_ROOT, script: FAKE_P4_SCRIPT, shim: FAKE_P4_SHIM, callsLog: FAKE_P4_CALLS }
}

// --------------------------------------------------------------------------- call log

/** Every recorded invocation, oldest first, as joined argv strings. */
export function readP4Calls() {
  if (!fs.existsSync(FAKE_P4_CALLS)) return []
  return fs
    .readFileSync(FAKE_P4_CALLS, 'utf8')
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter((line) => line !== '')
}

export function resetP4Calls() {
  fs.mkdirSync(path.dirname(FAKE_P4_CALLS), { recursive: true })
  fs.writeFileSync(FAKE_P4_CALLS, '')
}

// --------------------------------------------------------------------------- sandbox-safe exec

let ioCounter = 0

/** spawnSync with stdout/stderr redirected to files: this sandbox denies pipes. */
function spawnCapturedP4(file, args, options = {}) {
  const logDir = path.join(FAKE_P4_DIR, 'log')
  fs.mkdirSync(logDir, { recursive: true })
  const id = `${process.pid}-${++ioCounter}`
  const outFile = path.join(logDir, `${id}.out`)
  const errFile = path.join(logDir, `${id}.err`)
  const outFd = fs.openSync(outFile, 'w')
  const errFd = fs.openSync(errFile, 'w')
  let result
  try {
    result = spawnSync(file, args, {
      cwd: options.cwd,
      env: options.env,
      timeout: options.timeout,
      windowsHide: true,
      stdio: ['ignore', outFd, errFd],
    })
  } finally {
    fs.closeSync(outFd)
    fs.closeSync(errFd)
  }
  const stdout = fs.readFileSync(outFile)
  const stderr = fs.readFileSync(errFile)
  fs.rmSync(outFile, { force: true })
  fs.rmSync(errFile, { force: true })
  return { status: result.error ? -1 : result.status, stdout, stderr, error: result.error ?? null, signal: result.signal ?? null }
}

function execError(result) {
  if (result.error) {
    const code = result.error.code
    return Object.assign(new Error(result.error.message || 'spawn failed'), {
      code: code ?? -1,
      killed: code === 'ETIMEDOUT',
      signal: result.signal,
    })
  }
  return Object.assign(new Error(`p4 exited with ${result.status}`), { code: result.status })
}

function isFakeP4(file) {
  if (typeof file !== 'string' || file === '') return false
  const resolved = path.resolve(file).toLowerCase()
  if (resolved === FAKE_P4_SHIM.toLowerCase() || resolved === FAKE_P4_SCRIPT.toLowerCase()) return true
  return path.basename(resolved) === 'p4.cmd'
}

/**
 * An `execFile(file, args, options, callback)`-shaped seam that runs the fake p4
 * through the current node executable. Returns Buffers for both streams, like
 * `execFile` with `encoding: 'buffer'`, and a spawn-style error otherwise.
 *
 * @param {{ mode?: string, env?: object, p4Path?: string }} [options]
 */
export function createFakeP4ExecFile(options = {}) {
  return function fakeExecFile(file, args, opts, callback) {
    const callOptions = typeof opts === 'function' ? {} : opts ?? {}
    const done = typeof opts === 'function' ? opts : callback
    if (!isFakeP4(file)) {
      const error = Object.assign(new Error(`spawn ${file} ENOENT`), { code: 'ENOENT', killed: false, signal: null })
      done(error, Buffer.alloc(0), Buffer.alloc(0))
      return
    }
    const base = callOptions.env ?? options.env ?? process.env
    const env = { ...base, FAKE_P4_MODE: options.mode ?? base.FAKE_P4_MODE ?? P4_MODES.ok }
    const result = spawnCapturedP4(process.execPath, [FAKE_P4_SCRIPT, ...(args ?? [])], {
      cwd: callOptions.cwd ?? FAKE_P4_ROOT,
      env,
      timeout: callOptions.timeout,
    })
    done(result.status === 0 ? null : execError(result), result.stdout, result.stderr)
  }
}

/** The `run(args, cwd)` shape `lib/p4.js` expects, over the fake. */
export function createFakeP4Runner(options = {}) {
  const execFileFn = options.execFileFn ?? createFakeP4ExecFile(options)
  const p4Path = options.p4Path ?? FAKE_P4_SHIM
  return async function run(args, cwd) {
    return await new Promise((resolve) => {
      execFileFn(
        p4Path,
        args,
        { cwd: cwd ?? FAKE_P4_ROOT, timeout: options.timeoutMs ?? 20_000, env: options.env },
        (error, stdout, stderr) => {
          const status = error && typeof error.code === 'number' ? error.code : error ? -1 : 0
          resolve({
            status,
            stdout: stdout ?? Buffer.alloc(0),
            stderr: stderr ? stderr.toString('utf8') : error ? String(error.message) : '',
          })
        },
      )
    })
  }
}

